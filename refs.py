#!/usr/bin/env python3

# = не копирует, а привязывает имя к объекту
a = [1, 2, 3]
b = a
print(f"a = {a}, b = {b}")
print(f"a is b: {a is b}")  # True, так как это один и тот же объект
print(f"a == b: {a == b}")  # True, значения одинаковые

# += создаёт новый объект (для неизменяемых типов)
x = 1000
y = x
x += 1
print(f"x = {x}, y = {y}")
print(f"x is y: {x is y}")  # False, так как x перепривязался к новому объекту
print(f"x == y: {x == y}")  # False, значения разные

# == и is отвечают по-разному
c = int("1000")
d = int("1000")
print(f"c == d: {c == d}")  # True, значения равны
print(f"c is d: {c is d}")  # False, это разные объекты в памяти (кроме кэша малых чисел)
